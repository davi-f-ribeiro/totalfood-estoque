CREATE TABLE profiles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (btrim(name) <> '')
);

CREATE TABLE permissions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource text NOT NULL,
    action text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (resource, action),
    CHECK (btrim(resource) <> ''),
    CHECK (action IN ('read', 'write'))
);

CREATE TABLE profile_permissions (
    profile_id bigint NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
    permission_id bigint NOT NULL REFERENCES permissions(id) ON DELETE CASCADE,
    PRIMARY KEY (profile_id, permission_id)
);

CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login text NOT NULL UNIQUE,
    password_hash text NOT NULL,
    profile_id bigint NOT NULL REFERENCES profiles(id),
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (btrim(login) <> ''),
    CHECK (btrim(password_hash) <> '')
);

CREATE TABLE sessions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash text NOT NULL UNIQUE,
    csrf_token_hash text NOT NULL,
    expires_at timestamptz NOT NULL,
    revoked_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (btrim(token_hash) <> ''),
    CHECK (btrim(csrf_token_hash) <> '')
);

ALTER TABLE movements
    ADD COLUMN user_id bigint REFERENCES users(id);

CREATE INDEX idx_users_profile_id ON users(profile_id);
CREATE INDEX idx_profile_permissions_permission_id ON profile_permissions(permission_id);
CREATE INDEX idx_sessions_user_id ON sessions(user_id);
CREATE INDEX idx_sessions_valid_lookup ON sessions(token_hash, expires_at) WHERE revoked_at IS NULL;
CREATE INDEX idx_movements_user_id ON movements(user_id);

