DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM (
            SELECT item_id,warehouse_id,
                   sum(CASE WHEN direction='IN' THEN quantity ELSE -quantity END) AS balance
            FROM movement_lines
            GROUP BY item_id,warehouse_id
        ) b
        WHERE b.balance < 0
    ) THEN
        RAISE EXCEPTION 'cannot bootstrap stock lots with negative legacy balance';
    END IF;
END;
$$;

CREATE TABLE stock_lots (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id bigint NOT NULL REFERENCES inventory_items(id),
    warehouse_id bigint NOT NULL REFERENCES warehouses(id),
    source_movement_line_id bigint REFERENCES movement_lines(id),
    source_lot_id bigint REFERENCES stock_lots(id),
    initial_quantity numeric(14,3) NOT NULL,
    manufacturer_lot_code text,
    manufactured_at date,
    expires_at date,
    received_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    CHECK (initial_quantity > 0),
    CHECK (manufacturer_lot_code IS NULL OR btrim(manufacturer_lot_code) <> '')
);

CREATE TABLE stock_lot_allocations (
    movement_line_id bigint NOT NULL REFERENCES movement_lines(id),
    stock_lot_id bigint NOT NULL REFERENCES stock_lots(id),
    quantity numeric(14,3) NOT NULL,
    PRIMARY KEY (movement_line_id, stock_lot_id),
    CHECK (quantity > 0)
);

CREATE INDEX idx_stock_lots_item_warehouse_fefo
    ON stock_lots(item_id, warehouse_id, expires_at, received_at, id);

CREATE INDEX idx_stock_lot_allocations_lot_id
    ON stock_lot_allocations(stock_lot_id);

CREATE UNIQUE INDEX idx_stock_lots_entry_source_line_unique
    ON stock_lots(source_movement_line_id)
    WHERE source_movement_line_id IS NOT NULL AND source_lot_id IS NULL;

CREATE UNIQUE INDEX idx_stock_lots_transfer_source_unique
    ON stock_lots(source_movement_line_id,source_lot_id)
    WHERE source_movement_line_id IS NOT NULL AND source_lot_id IS NOT NULL;


-- Existing stock predates internal lot allocation. Materialize only its
-- current physical balance, without inventing a supplier/manufacturer lot or
-- claiming a historical source movement.
INSERT INTO stock_lots (
    item_id,
    warehouse_id,
    source_movement_line_id,
    initial_quantity,
    received_at
)
SELECT
    ml.item_id,
    ml.warehouse_id,
    NULL,
    sum(CASE WHEN ml.direction='IN' THEN ml.quantity ELSE -ml.quantity END),
    statement_timestamp()
FROM movement_lines ml
GROUP BY ml.item_id,ml.warehouse_id
HAVING sum(CASE WHEN ml.direction='IN' THEN ml.quantity ELSE -ml.quantity END) > 0;
