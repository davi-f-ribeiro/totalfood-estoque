-- Planner de cardápio (docs/planner-cardapio-contract.md).
-- Nenhuma tabela guarda custo calculado, exceto o retrato do plano aprovado.

-- Atributos de planejamento da ficha técnica. A ficha descreve a porção de uma
-- pessoa: portion_size é o peso pronto dessa porção. Função e etiquetas são texto
-- livre normalizado (minúsculas), usados pelo modelo de refeição e pelas regras.
ALTER TABLE recipes
    ADD COLUMN meal_function text,
    ADD COLUMN portion_size numeric(14,3),
    ADD COLUMN portion_unit text,
    ADD COLUMN tags text[] NOT NULL DEFAULT '{}',
    ADD CONSTRAINT recipes_meal_function_check CHECK (meal_function IS NULL OR (meal_function = lower(btrim(meal_function)) AND meal_function <> '')),
    ADD CONSTRAINT recipes_portion_size_check CHECK (portion_size IS NULL OR portion_size > 0),
    ADD CONSTRAINT recipes_portion_unit_check CHECK (portion_unit IS NULL OR portion_unit IN ('g', 'ml', 'un')),
    ADD CONSTRAINT recipes_portion_pair_check CHECK ((portion_size IS NULL) = (portion_unit IS NULL));

CREATE TABLE customer_groups (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    active boolean NOT NULL DEFAULT true,
    version bigint NOT NULL DEFAULT 1 CHECK (version > 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (btrim(name) <> '')
);

CREATE UNIQUE INDEX idx_customer_groups_normalized_name_unique
    ON customer_groups (lower(btrim(name)));

-- Refeições contratadas pelo grupo e o preço por pessoa de cada uma.
CREATE TABLE customer_group_meals (
    group_id bigint NOT NULL REFERENCES customer_groups(id) ON DELETE CASCADE,
    meal text NOT NULL CHECK (meal IN ('cafe', 'almoco', 'lanche', 'jantar')),
    price numeric(14,2) NOT NULL CHECK (price > 0),
    PRIMARY KEY (group_id, meal)
);

-- Modelo de refeição do grupo: funções, quantas opções de cada uma, per capita
-- pronto do contrato e adesão padrão (percentual que consome cada opção).
CREATE TABLE customer_group_menu (
    group_id bigint NOT NULL,
    meal text NOT NULL,
    meal_function text NOT NULL CHECK (meal_function = lower(btrim(meal_function)) AND meal_function <> ''),
    sort_order smallint NOT NULL DEFAULT 0,
    options smallint NOT NULL DEFAULT 1 CHECK (options BETWEEN 1 AND 9),
    per_capita numeric(14,3) NOT NULL CHECK (per_capita > 0),
    per_capita_unit text NOT NULL CHECK (per_capita_unit IN ('g', 'ml', 'un')),
    adhesion numeric(5,2) NOT NULL DEFAULT 100 CHECK (adhesion > 0 AND adhesion <= 100),
    PRIMARY KEY (group_id, meal, meal_function),
    FOREIGN KEY (group_id, meal) REFERENCES customer_group_meals(group_id, meal) ON DELETE CASCADE
);

-- Regras do grupo. exists_with / exists_without / none_with: quando a refeição
-- tiver uma ficha com when_tag (ou sempre, se vazio), a função exige uma ficha
-- com a etiqueta, uma ficha sem a etiqueta, ou nenhuma ficha com a etiqueta.
-- no_repeat: a função não repete a mesma ficha (ou a mesma etiqueta) em days dias seguidos.
CREATE TABLE customer_group_rules (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id bigint NOT NULL REFERENCES customer_groups(id) ON DELETE CASCADE,
    kind text NOT NULL CHECK (kind IN ('exists_with', 'exists_without', 'none_with', 'no_repeat')),
    when_tag text,
    meal_function text NOT NULL CHECK (meal_function = lower(btrim(meal_function)) AND meal_function <> ''),
    tag text,
    days smallint,
    CHECK (when_tag IS NULL OR (when_tag = lower(btrim(when_tag)) AND when_tag <> '')),
    CHECK (tag IS NULL OR (tag = lower(btrim(tag)) AND tag <> '')),
    CHECK (kind = 'no_repeat' OR tag IS NOT NULL),
    CHECK ((kind = 'no_repeat') = (days IS NOT NULL)),
    CHECK (days IS NULL OR days BETWEEN 1 AND 30)
);

CREATE TABLE menu_plans (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (btrim(name) <> ''),
    start_date date NOT NULL,
    end_date date NOT NULL,
    target_cmv numeric(5,2) NOT NULL CHECK (target_cmv > 0 AND target_cmv <= 100),
    daily_tolerance numeric(5,2) NOT NULL DEFAULT 5 CHECK (daily_tolerance >= 0 AND daily_tolerance <= 100),
    scale_tolerance numeric(5,2) NOT NULL DEFAULT 3 CHECK (scale_tolerance >= 0 AND scale_tolerance <= 100),
    status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'approved')),
    approved_at timestamptz,
    approved_by bigint REFERENCES users(id),
    created_by bigint REFERENCES users(id),
    version bigint NOT NULL DEFAULT 1 CHECK (version > 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (end_date >= start_date AND end_date - start_date <= 62),
    CHECK ((status = 'approved') = (approved_at IS NOT NULL))
);

-- Premissa (pessoas previstas) e quantidade real por grupo, dia e refeição.
-- A quantidade real tem versão própria: é lançada depois, sem tocar a premissa.
CREATE TABLE menu_plan_meals (
    plan_id bigint NOT NULL REFERENCES menu_plans(id) ON DELETE CASCADE,
    group_id bigint NOT NULL REFERENCES customer_groups(id),
    day date NOT NULL,
    meal text NOT NULL CHECK (meal IN ('cafe', 'almoco', 'lanche', 'jantar')),
    people integer NOT NULL CHECK (people >= 0),
    actual_people integer CHECK (actual_people >= 0),
    actual_version bigint NOT NULL DEFAULT 0 CHECK (actual_version >= 0),
    actual_by bigint REFERENCES users(id),
    actual_at timestamptz,
    PRIMARY KEY (plan_id, group_id, day, meal)
);

CREATE TABLE menu_plan_positions (
    plan_id bigint NOT NULL,
    group_id bigint NOT NULL,
    day date NOT NULL,
    meal text NOT NULL,
    meal_function text NOT NULL,
    option_no smallint NOT NULL CHECK (option_no BETWEEN 1 AND 9),
    recipe_id bigint REFERENCES recipes(id),
    adhesion numeric(5,2) NOT NULL CHECK (adhesion > 0 AND adhesion <= 100),
    locked boolean NOT NULL DEFAULT false,
    PRIMARY KEY (plan_id, group_id, day, meal, meal_function, option_no),
    FOREIGN KEY (plan_id, group_id, day, meal) REFERENCES menu_plan_meals(plan_id, group_id, day, meal) ON DELETE CASCADE,
    CHECK (NOT locked OR recipe_id IS NOT NULL)
);

-- Retrato da aprovação (previsto): custo e receita por refeição, consumo por item e dia.
CREATE TABLE menu_plan_snapshot_meals (
    plan_id bigint NOT NULL,
    group_id bigint NOT NULL,
    day date NOT NULL,
    meal text NOT NULL,
    people integer NOT NULL,
    price numeric(14,2) NOT NULL,
    cost numeric(16,4) NOT NULL,
    PRIMARY KEY (plan_id, group_id, day, meal),
    FOREIGN KEY (plan_id, group_id, day, meal) REFERENCES menu_plan_meals(plan_id, group_id, day, meal) ON DELETE CASCADE
);

CREATE TABLE menu_plan_snapshot_items (
    plan_id bigint NOT NULL REFERENCES menu_plans(id) ON DELETE CASCADE,
    item_id bigint NOT NULL REFERENCES inventory_items(id),
    day date NOT NULL,
    quantity numeric(16,4) NOT NULL CHECK (quantity > 0),
    unit_cost numeric(14,4) NOT NULL CHECK (unit_cost >= 0),
    cost_source text NOT NULL CHECK (cost_source IN ('estoque', 'ultima_compra')),
    PRIMARY KEY (plan_id, item_id, day)
);

CREATE TABLE purchase_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id bigint NOT NULL REFERENCES menu_plans(id),
    operation_id text NOT NULL UNIQUE CHECK (btrim(operation_id) <> ''),
    created_by bigint REFERENCES users(id),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE purchase_request_lines (
    request_id bigint NOT NULL REFERENCES purchase_requests(id) ON DELETE CASCADE,
    item_id bigint NOT NULL REFERENCES inventory_items(id),
    need numeric(16,4) NOT NULL CHECK (need > 0),
    balance numeric(16,4) NOT NULL,
    quantity numeric(16,4) NOT NULL CHECK (quantity > 0),
    runout_date date NOT NULL,
    PRIMARY KEY (request_id, item_id)
);

