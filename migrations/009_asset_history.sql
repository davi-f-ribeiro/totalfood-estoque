CREATE TABLE asset_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id text NOT NULL UNIQUE,
    request_hash text NOT NULL,
    asset_id bigint NOT NULL REFERENCES assets(id),
    event_type text NOT NULL,
    origin_warehouse_id bigint REFERENCES warehouses(id),
    destination_warehouse_id bigint REFERENCES warehouses(id),
    old_status text,
    new_status text,
    user_id bigint NOT NULL REFERENCES users(id),
    occurred_at timestamptz NOT NULL DEFAULT now(),
    CHECK (btrim(operation_id) <> ''),
    CHECK (btrim(request_hash) <> ''),
    CHECK (event_type IN ('MOVE', 'STATUS')),
    CHECK (old_status IS NULL OR old_status IN ('ATIVO', 'EM_MANUTENCAO', 'BAIXADO')),
    CHECK (new_status IS NULL OR new_status IN ('ATIVO', 'EM_MANUTENCAO', 'BAIXADO'))
);

CREATE INDEX idx_asset_events_asset_id ON asset_events(asset_id);
CREATE INDEX idx_asset_events_user_id ON asset_events(user_id);
CREATE INDEX idx_asset_events_origin_warehouse_id ON asset_events(origin_warehouse_id);
CREATE INDEX idx_asset_events_destination_warehouse_id ON asset_events(destination_warehouse_id);

INSERT INTO permissions (resource, action) VALUES
    ('assets', 'read'),
    ('assets', 'write')
ON CONFLICT (resource, action) DO NOTHING;

INSERT INTO profile_permissions (profile_id, permission_id)
SELECT p.id, perm.id
FROM profiles p
JOIN permissions perm ON perm.resource = 'assets' AND perm.action IN ('read', 'write')
WHERE p.name = 'Diretor'
ON CONFLICT DO NOTHING;
