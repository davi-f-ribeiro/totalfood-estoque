    DROP CONSTRAINT movements_movement_type_check;

ALTER TABLE movements
    ADD CONSTRAINT movements_movement_type_check
    CHECK (movement_type IN ('ENTRADA', 'SAIDA', 'TRANSFERENCIA', 'AJUSTE'));

CREATE TABLE inventory_stock_adjustments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    validation_id bigint NOT NULL,
    sku_id bigint NOT NULL,
    movement_id bigint NOT NULL REFERENCES movements(id),
    approved_by_user_id bigint NOT NULL REFERENCES users(id),
    applied_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (validation_id, sku_id)
        REFERENCES inventory_validation_lines(validation_id, sku_id),
    UNIQUE (validation_id, sku_id),
    UNIQUE (movement_id)
);

INSERT INTO permissions (resource, action)
VALUES ('stock_adjustment', 'write')
ON CONFLICT (resource, action) DO NOTHING;
