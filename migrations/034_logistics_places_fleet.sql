-- Fase 2 da cadeia de suprimentos: locais de entrega e coleta, veículos e motoristas.
-- Cadastros puros: nada aqui mexe em saldo, custo ou movimento de estoque.
-- Coordenadas ficam em numeric para não exigir PostGIS; distâncias são calculadas no Go.

CREATE TABLE places (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (btrim(name) <> ''),
    kind text NOT NULL CHECK (kind IN ('cliente', 'fornecedor', 'deposito', 'outro')),
    customer_id bigint REFERENCES customers(id),
    warehouse_id bigint REFERENCES warehouses(id),
    address text NOT NULL CHECK (btrim(address) <> ''),
    city text CHECK (city IS NULL OR btrim(city) <> ''),
    latitude numeric(9,6) CHECK (latitude BETWEEN -90 AND 90),
    longitude numeric(9,6) CHECK (longitude BETWEEN -180 AND 180),
    window_start time,
    window_end time,
    contact text CHECK (contact IS NULL OR btrim(contact) <> ''),
    access_notes text CHECK (access_notes IS NULL OR btrim(access_notes) <> ''),
    active boolean NOT NULL DEFAULT true,
    version bigint NOT NULL DEFAULT 1 CHECK (version > 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT places_customer_matches_kind CHECK ((kind = 'cliente') = (customer_id IS NOT NULL)),
    CONSTRAINT places_warehouse_matches_kind CHECK ((kind = 'deposito') = (warehouse_id IS NOT NULL)),
    CONSTRAINT places_coordinates_pair CHECK ((latitude IS NULL) = (longitude IS NULL)),
    CONSTRAINT places_window_pair CHECK ((window_start IS NULL) = (window_end IS NULL)),
    CONSTRAINT places_window_order CHECK (window_start IS NULL OR window_start < window_end)
);

CREATE UNIQUE INDEX idx_places_normalized_name_unique ON places (lower(btrim(name)));

CREATE TABLE vehicles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Placa sem hífen, maiúscula: padrão antigo (ABC1234) ou Mercosul (ABC1D23).
    plate text NOT NULL CHECK (plate ~ '^[A-Z]{3}[0-9][A-Z0-9][0-9]{2}$'),
    description text NOT NULL CHECK (btrim(description) <> ''),
    asset_id bigint UNIQUE REFERENCES assets(id),
    capacity_kg numeric(10,2) NOT NULL CHECK (capacity_kg > 0),
    capacity_boxes integer CHECK (capacity_boxes > 0),
    refrigerated boolean NOT NULL DEFAULT false,
    active boolean NOT NULL DEFAULT true,
    version bigint NOT NULL DEFAULT 1 CHECK (version > 0),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX idx_vehicles_plate_unique ON vehicles (plate);

CREATE TABLE drivers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (btrim(name) <> ''),
    phone text CHECK (phone IS NULL OR btrim(phone) <> ''),
    license_number text CHECK (license_number IS NULL OR license_number ~ '^[0-9]{11}$'),
    license_category text CHECK (license_category IS NULL OR license_category IN ('A', 'B', 'C', 'D', 'E', 'AB', 'AC', 'AD', 'AE')),
    license_expires_at date,
    -- Login do motorista: opcional nesta fase; o app do motorista chega na fase de expedição.
    user_id bigint UNIQUE REFERENCES users(id),
    default_vehicle_id bigint REFERENCES vehicles(id),
    active boolean NOT NULL DEFAULT true,
    version bigint NOT NULL DEFAULT 1 CHECK (version > 0),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX idx_drivers_normalized_name_unique ON drivers (lower(btrim(name)));
CREATE UNIQUE INDEX idx_drivers_license_number_unique ON drivers (license_number);

