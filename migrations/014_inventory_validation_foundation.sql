CREATE TABLE inventory_validations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type text NOT NULL,
    warehouse_id bigint NOT NULL REFERENCES warehouses(id),
    status text NOT NULL DEFAULT 'OPEN',
    responsible_user_id bigint NOT NULL REFERENCES users(id),
    started_at timestamptz,
    completed_at timestamptz,
    cancelled_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (type IN ('TOTAL', 'BLIND')),
    CHECK (status IN ('OPEN', 'COUNTING', 'REVIEW', 'COMPLETED', 'CANCELLED')),
    CHECK (completed_at IS NULL OR status = 'COMPLETED'),
    CHECK (cancelled_at IS NULL OR status = 'CANCELLED')
);

CREATE TABLE inventory_validation_lines (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    validation_id bigint NOT NULL REFERENCES inventory_validations(id),
    sku_id bigint NOT NULL REFERENCES product_skus(id),
    system_quantity_snapshot numeric(14,3),
    physical_quantity numeric(14,3),
    difference numeric(14,3),
    status text NOT NULL DEFAULT 'OPEN',
    counted_by_user_id bigint REFERENCES users(id),
    counted_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (validation_id, sku_id),
    CHECK (status IN ('OPEN', 'COUNTED', 'DIVERGENT', 'REVIEWED'))
);

CREATE INDEX idx_inventory_validations_warehouse_id
    ON inventory_validations(warehouse_id);

CREATE INDEX idx_inventory_validations_responsible_user_id
    ON inventory_validations(responsible_user_id);

CREATE INDEX idx_inventory_validation_lines_validation_id
    ON inventory_validation_lines(validation_id);

CREATE INDEX idx_inventory_validation_lines_sku_id
    ON inventory_validation_lines(sku_id);

CREATE INDEX idx_inventory_validation_lines_counted_by_user_id
    ON inventory_validation_lines(counted_by_user_id);

INSERT INTO permissions (resource, action) VALUES
    ('inventory_validation', 'read'),
    ('inventory_validation', 'write')
ON CONFLICT (resource, action) DO NOTHING;

INSERT INTO profile_permissions (profile_id, permission_id)
SELECT p.id, perm.id
FROM profiles p
JOIN permissions perm
    ON perm.resource = 'inventory_validation'
   AND perm.action IN ('read', 'write')
WHERE p.name = 'Diretor'
ON CONFLICT DO NOTHING;
