-- Dados de localização brutos, recebidos independentemente do estado da rota.
-- gps_at é nulo se o fuso/relógio não estiverem configurados ou se a data for inválida.
CREATE TABLE geofence_positions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id bigint NOT NULL REFERENCES vehicles(id),
    remote_id text NOT NULL,
    latitude numeric(9,6) NOT NULL,
    longitude numeric(9,6) NOT NULL,
    gps_at timestamptz,
    raw_device_time text,
    received_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT geofence_positions_coords CHECK (latitude BETWEEN -90 AND 90 AND longitude BETWEEN -180 AND 180)
);
CREATE UNIQUE INDEX geofence_positions_dedupe
    ON geofence_positions(vehicle_id, raw_device_time, latitude, longitude) NULLS NOT DISTINCT;
CREATE INDEX geofence_positions_vehicle_time ON geofence_positions(vehicle_id, gps_at DESC, id DESC);

-- cursor id impede reprocessamento; duas leituras distintas confirmam travessia.
-- stop_order_id 0 representa o depósito, outros IDs representam ordens de entrega.
CREATE TABLE geofence_progress (
    route_id bigint NOT NULL REFERENCES routes(id) ON DELETE CASCADE,
    stop_order_id bigint NOT NULL DEFAULT 0 CHECK (stop_order_id >= 0),
    last_position_id bigint REFERENCES geofence_positions(id),
    last_gps_at timestamptz,
    inside_seen boolean NOT NULL DEFAULT false,
    confirmation_count smallint NOT NULL DEFAULT 0 CHECK (confirmation_count >= 0),
    candidate_at timestamptz,
    candidate_position_id bigint REFERENCES geofence_positions(id),
    PRIMARY KEY (route_id, stop_order_id)
);

CREATE TABLE geofence_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id bigint NOT NULL REFERENCES routes(id),
    stop_order_id bigint NOT NULL DEFAULT 0 CHECK (stop_order_id >= 0),
    vehicle_id bigint NOT NULL REFERENCES vehicles(id),
    position_id bigint NOT NULL REFERENCES geofence_positions(id),
    first_position_id bigint NOT NULL REFERENCES geofence_positions(id),
    center_latitude numeric(9,6) NOT NULL,
    center_longitude numeric(9,6) NOT NULL,
    radius_m integer NOT NULL,
    kind text NOT NULL CHECK (kind IN ('saida_deposito','chegada_cliente')),
    occurred_at timestamptz NOT NULL,
    detected_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (route_id, kind, stop_order_id),
    CONSTRAINT geofence_events_kind_stop_check CHECK (
        (kind='saida_deposito' AND stop_order_id=0) OR
        (kind='chegada_cliente' AND stop_order_id>0))
);
CREATE INDEX geofence_events_route ON geofence_events(route_id, occurred_at);
