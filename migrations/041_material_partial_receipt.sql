-- Recebimento parcial de requisições. A cozinha informa quanto recebeu de cada
-- entrega; o que faltou fica como divergência até a gerência registrar o
-- recebimento do restante. Nada aqui movimenta estoque: a saída continua
-- sendo a da entrega (material_request_deliveries.movement_id).

ALTER TABLE material_request_deliveries
  ADD COLUMN received_quantity numeric(14,3),
  ADD COLUMN divergence_reason text NOT NULL DEFAULT '' CHECK(length(divergence_reason) <= 500);

-- Entregas já conferidas foram recebidas por inteiro.
UPDATE material_request_deliveries SET received_quantity=quantity WHERE received_at IS NOT NULL;

ALTER TABLE material_request_deliveries
  ADD CONSTRAINT material_request_deliveries_received_quantity_check
    CHECK(received_quantity IS NULL OR (received_quantity >= 0 AND received_quantity <= quantity)),
  ADD CONSTRAINT material_request_deliveries_received_state_check
    CHECK((received_at IS NULL) = (received_quantity IS NULL));

-- Uma linha por confirmação: a conferência da cozinha (RECEBIMENTO, uma por
-- entrega) e cada conciliação posterior (CONCILIACAO). A soma das linhas é a
-- quantidade recebida da entrega.
CREATE TABLE material_request_receipts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  delivery_id bigint NOT NULL REFERENCES material_request_deliveries(id),
  kind text NOT NULL CHECK(kind IN ('RECEBIMENTO','CONCILIACAO')),
  quantity numeric(14,3) NOT NULL CHECK(quantity >= 0),
  notes text NOT NULL DEFAULT '' CHECK(length(notes) <= 500),
  operation_id text UNIQUE CHECK(operation_id IS NULL OR length(btrim(operation_id)) BETWEEN 1 AND 120),
  request_hash text NOT NULL DEFAULT '',
  actor_id bigint NOT NULL REFERENCES users(id),
  occurred_at timestamptz NOT NULL DEFAULT now(),
  CHECK(kind='RECEBIMENTO' OR (quantity > 0 AND operation_id IS NOT NULL))
);
CREATE UNIQUE INDEX idx_material_receipts_first ON material_request_receipts(delivery_id) WHERE kind='RECEBIMENTO';
CREATE INDEX idx_material_receipts_delivery ON material_request_receipts(delivery_id,id);

INSERT INTO material_request_receipts(delivery_id,kind,quantity,actor_id,occurred_at)
SELECT id,'RECEBIMENTO',quantity,received_by,received_at
FROM material_request_deliveries WHERE received_at IS NOT NULL;

ALTER TABLE material_requests DROP CONSTRAINT material_requests_status_check;
ALTER TABLE material_requests ADD CONSTRAINT material_requests_status_check CHECK(status IN
  ('PENDENTE','EM_SEPARACAO','ENTREGA_PARCIAL','ENTREGUE','RECEBIDA_COM_DIVERGENCIA','RECEBIDA','CANCELADA'));

ALTER TABLE material_request_events DROP CONSTRAINT material_request_events_action_check;
ALTER TABLE material_request_events ADD CONSTRAINT material_request_events_action_check CHECK(action IN
  ('CRIADA','RESERVADA','LIBERADA','ENTREGUE','RECEBIDA','DIVERGENCIA','CONCILIADA','CANCELADA'));

-- Conciliar divergência é decisão da gerência: só Diretor e Gerente.
INSERT INTO permissions(resource,action) VALUES ('material_divergences','write')
ON CONFLICT (resource,action) DO NOTHING;

INSERT INTO profile_permissions(profile_id,permission_id)
SELECT p.id,perm.id
FROM profiles p JOIN permissions perm ON perm.resource='material_divergences' AND perm.action='write'
WHERE p.name IN ('Diretor','Gerente')
ON CONFLICT DO NOTHING;
