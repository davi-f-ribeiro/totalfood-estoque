CREATE TABLE customers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    active boolean NOT NULL DEFAULT true,
    version bigint NOT NULL DEFAULT 1 CHECK (version > 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (btrim(name) <> '')
);

CREATE UNIQUE INDEX idx_customers_normalized_name_unique
    ON customers (lower(btrim(name)));

CREATE TABLE recipes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    portions numeric(14,3) NOT NULL CHECK (portions > 0),
    notes text,
    active boolean NOT NULL DEFAULT true,
    version bigint NOT NULL DEFAULT 1 CHECK (version > 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (btrim(name) <> ''),
    CHECK (notes IS NULL OR btrim(notes) <> '')
);

CREATE UNIQUE INDEX idx_recipes_normalized_name_unique
    ON recipes (lower(btrim(name)));

-- quantity é a quantidade líquida por receita, na unidade do item.
-- correction_factor é a perda de limpeza ou cocção: a quantidade bruta
-- consumida é quantity * correction_factor.
CREATE TABLE recipe_lines (
    recipe_id bigint NOT NULL REFERENCES recipes(id) ON DELETE CASCADE,
    item_id bigint NOT NULL REFERENCES inventory_items(id),
    quantity numeric(14,4) NOT NULL CHECK (quantity > 0),
    correction_factor numeric(8,4) NOT NULL DEFAULT 1 CHECK (correction_factor >= 1),
    PRIMARY KEY (recipe_id, item_id)
);

CREATE TABLE recipe_customer_prices (
    recipe_id bigint NOT NULL REFERENCES recipes(id) ON DELETE CASCADE,
    customer_id bigint NOT NULL REFERENCES customers(id),
    sale_price numeric(14,2) NOT NULL CHECK (sale_price > 0),
    PRIMARY KEY (recipe_id, customer_id)
);

INSERT INTO permissions (resource, action)
VALUES ('costs', 'read'), ('costs', 'write')
ON CONFLICT (resource, action) DO NOTHING;

INSERT INTO profile_permissions (profile_id, permission_id)
SELECT p.id, perm.id
FROM profiles p
JOIN permissions perm ON perm.resource = 'costs'
WHERE p.name = 'Diretor'
ON CONFLICT DO NOTHING;

