-- Warehouse administration foundation.
-- Warehouses are historical entities: lifecycle is active/inactive; deletion is intentionally unsupported.

INSERT INTO permissions (resource, action)
VALUES ('warehouses', 'write')
ON CONFLICT (resource, action) DO NOTHING;

INSERT INTO profile_permissions (profile_id, permission_id)
SELECT p.id, perm.id
FROM profiles p
JOIN permissions perm ON perm.resource='warehouses' AND perm.action='write'
WHERE p.name='Diretor'
ON CONFLICT DO NOTHING;

-- Tracking invariant: names are permanent identifiers for people and reports.
-- Reject duplicates even when case or surrounding whitespace differs.
CREATE UNIQUE INDEX warehouses_name_tracking_unique
    ON warehouses (lower(btrim(name)));

CREATE TABLE warehouse_audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warehouse_id bigint NOT NULL REFERENCES warehouses(id),
    action text NOT NULL CHECK (action IN ('CREATED','ACTIVATED','DEACTIVATED')),
    user_id bigint REFERENCES users(id),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_warehouse_audit_warehouse_id_created_at
    ON warehouse_audit(warehouse_id, created_at DESC);

CREATE OR REPLACE FUNCTION prevent_warehouse_delete()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'warehouses cannot be deleted; deactivate instead';
END;
$$;

CREATE TRIGGER warehouses_no_delete
BEFORE DELETE ON warehouses
FOR EACH ROW EXECUTE FUNCTION prevent_warehouse_delete();


-- A current asset location is operational state. Never allow a new/current
-- asset assignment to an inactive warehouse, including direct SQL writes.
CREATE OR REPLACE FUNCTION enforce_active_asset_warehouse()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    warehouse_active boolean;
BEGIN
    IF NEW.current_warehouse_id IS NULL THEN
        RETURN NEW;
    END IF;

    SELECT active
      INTO warehouse_active
      FROM warehouses
     WHERE id = NEW.current_warehouse_id
     FOR UPDATE;

    IF NOT FOUND OR NOT warehouse_active THEN
        RAISE EXCEPTION 'asset warehouse inactive or not found';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER assets_active_warehouse
BEFORE INSERT OR UPDATE OF current_warehouse_id ON assets
FOR EACH ROW EXECUTE FUNCTION enforce_active_asset_warehouse();


-- Deactivation is a database invariant, not only an HTTP rule.
CREATE OR REPLACE FUNCTION enforce_warehouse_deactivation_empty()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.active AND NOT NEW.active THEN
        IF EXISTS (
            SELECT 1
            FROM movement_lines
            WHERE warehouse_id = OLD.id
            GROUP BY sku_id
            HAVING SUM(CASE direction WHEN 'IN' THEN quantity ELSE -quantity END) <> 0
        ) OR EXISTS (
            SELECT 1
            FROM assets
            WHERE current_warehouse_id = OLD.id
        ) THEN
            RAISE EXCEPTION 'warehouse not empty';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER warehouses_deactivate_only_empty
BEFORE UPDATE OF active ON warehouses
FOR EACH ROW EXECUTE FUNCTION enforce_warehouse_deactivation_empty();


-- Stock movements must never create new operational history in an inactive
-- warehouse, even when a write bypasses the HTTP layer.
CREATE OR REPLACE FUNCTION enforce_active_movement_warehouse()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    warehouse_active boolean;
BEGIN
    SELECT active
      INTO warehouse_active
      FROM warehouses
     WHERE id = NEW.warehouse_id
     FOR UPDATE;

    IF NOT FOUND OR NOT warehouse_active THEN
        RAISE EXCEPTION 'movement warehouse inactive or not found';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER movement_lines_active_warehouse
BEFORE INSERT OR UPDATE ON movement_lines
FOR EACH ROW EXECUTE FUNCTION enforce_active_movement_warehouse();


-- Warehouse names are historical identifiers. Renaming is intentionally
-- unsupported for the same traceability reason as deletion.
CREATE OR REPLACE FUNCTION prevent_warehouse_rename()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.name IS DISTINCT FROM OLD.name THEN
        RAISE EXCEPTION 'warehouse names cannot be changed';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER warehouses_no_rename
BEFORE UPDATE OF name ON warehouses
FOR EACH ROW EXECUTE FUNCTION prevent_warehouse_rename();
