-- Warehouse administration foundation.
-- Warehouses are historical entities: lifecycle is active/inactive; deletion is intentionally unsupported.

INSERT INTO permissions (resource, action)
VALUES ('warehouses', 'write')
ON CONFLICT (resource, action) DO NOTHING;

INSERT INTO profile_permissions (profile_id, permission_id)
SELECT p.id, perm.id
FROM profiles p
JOIN permissions perm ON perm.resource='warehouses' AND perm.action='write'
WHERE p.name='Diretor'
ON CONFLICT DO NOTHING;

CREATE TABLE warehouse_audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warehouse_id bigint NOT NULL REFERENCES warehouses(id),
    action text NOT NULL CHECK (action IN ('CREATED','ACTIVATED','DEACTIVATED')),
    user_id bigint REFERENCES users(id),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_warehouse_audit_warehouse_id_created_at
    ON warehouse_audit(warehouse_id, created_at DESC);

CREATE OR REPLACE FUNCTION prevent_warehouse_delete()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'warehouses cannot be deleted; deactivate instead';
END;
$$;

CREATE TRIGGER warehouses_no_delete
BEFORE DELETE ON warehouses
FOR EACH ROW EXECUTE FUNCTION prevent_warehouse_delete();
