CREATE TABLE warehouses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legacy_id text UNIQUE,
    name text NOT NULL UNIQUE,
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (btrim(name) <> '')
);

CREATE TABLE units (
    code text PRIMARY KEY,
    name text NOT NULL,
    magnitude text,
    active boolean NOT NULL DEFAULT true,
    CHECK (btrim(code) <> ''),
    CHECK (btrim(name) <> ''),
    CHECK (magnitude IS NULL OR btrim(magnitude) <> '')
);

CREATE TABLE categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legacy_id text UNIQUE,
    name text NOT NULL UNIQUE,
    active boolean NOT NULL DEFAULT true,
    CHECK (btrim(name) <> '')
);

CREATE TABLE inventory_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legacy_id text UNIQUE,
    name text NOT NULL,
    category_id bigint REFERENCES categories(id),
    unit_code text NOT NULL REFERENCES units(code),
    minimum_stock numeric(14,3) NOT NULL DEFAULT 0,
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (btrim(name) <> ''),
    CHECK (minimum_stock >= 0)
);

CREATE TABLE product_skus (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legacy_id text UNIQUE,
    item_id bigint NOT NULL REFERENCES inventory_items(id),
    brand text,
    name text,
    barcode text UNIQUE,
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (brand IS NULL OR btrim(brand) <> ''),
    CHECK (name IS NULL OR btrim(name) <> ''),
    CHECK (barcode IS NULL OR btrim(barcode) <> '')
);

CREATE TABLE movements (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legacy_id text UNIQUE,
    movement_type text NOT NULL,
    occurred_at timestamptz NOT NULL DEFAULT now(),
    document_number text,
    supplier_name text,
    notes text,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (movement_type IN ('ENTRADA', 'SAIDA', 'TRANSFERENCIA')),
    CHECK (document_number IS NULL OR btrim(document_number) <> ''),
    CHECK (supplier_name IS NULL OR btrim(supplier_name) <> '')
);

CREATE TABLE movement_lines (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movement_id bigint NOT NULL REFERENCES movements(id) ON DELETE CASCADE,
    sku_id bigint NOT NULL REFERENCES product_skus(id),
    warehouse_id bigint NOT NULL REFERENCES warehouses(id),
    direction text NOT NULL,
    quantity numeric(14,3) NOT NULL,
    unit_cost numeric(14,4),
    lot_code text,
    CHECK (direction IN ('IN', 'OUT')),
    CHECK (quantity > 0),
    CHECK (unit_cost IS NULL OR unit_cost >= 0),
    CHECK (lot_code IS NULL OR btrim(lot_code) <> '')
);

CREATE TABLE asset_types (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legacy_id text UNIQUE,
    name text NOT NULL UNIQUE,
    unit_code text REFERENCES units(code),
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (btrim(name) <> '')
);

CREATE TABLE assets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legacy_id text UNIQUE,
    asset_type_id bigint NOT NULL REFERENCES asset_types(id),
    tag text NOT NULL UNIQUE,
    status text NOT NULL,
    current_warehouse_id bigint REFERENCES warehouses(id),
    acquired_at date,
    acquisition_document text,
    acquisition_unit_cost numeric(14,4),
    lot_code text,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (btrim(tag) <> ''),
    CHECK (status IN ('ATIVO', 'EM_MANUTENCAO', 'BAIXADO')),
    CHECK (status <> 'ATIVO' OR current_warehouse_id IS NOT NULL),
    CHECK (acquisition_unit_cost IS NULL OR acquisition_unit_cost >= 0),
    CHECK (acquisition_document IS NULL OR btrim(acquisition_document) <> ''),
    CHECK (lot_code IS NULL OR btrim(lot_code) <> '')
);

CREATE INDEX idx_inventory_items_category_id ON inventory_items(category_id);
CREATE INDEX idx_inventory_items_unit_code ON inventory_items(unit_code);
CREATE INDEX idx_product_skus_item_id ON product_skus(item_id);
