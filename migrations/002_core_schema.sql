CREATE OR REPLACE FUNCTION validate_movement_consistency(target_movement_id bigint)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    mt text;
    line_count integer;
    in_count integer;
    out_count integer;
    distinct_skus integer;
    distinct_quantities integer;
    distinct_warehouses integer;
BEGIN
    SELECT movement_type INTO mt FROM movements WHERE id = target_movement_id;
    IF mt IS NULL THEN
        RETURN;
    END IF;

    SELECT
        count(*),
        count(*) FILTER (WHERE direction = 'IN'),
        count(*) FILTER (WHERE direction = 'OUT'),
        count(DISTINCT sku_id),
        count(DISTINCT quantity),
        count(DISTINCT warehouse_id)
    INTO line_count, in_count, out_count, distinct_skus, distinct_quantities, distinct_warehouses
    FROM movement_lines
    WHERE movement_id = target_movement_id;

    IF mt = 'ENTRADA' AND (line_count < 1 OR out_count <> 0) THEN
        RAISE EXCEPTION 'invalid ENTRADA movement';
    ELSIF mt = 'SAIDA' AND (line_count < 1 OR in_count <> 0) THEN
        RAISE EXCEPTION 'invalid SAIDA movement';
    ELSIF mt = 'TRANSFERENCIA' AND (
        line_count <> 2 OR in_count <> 1 OR out_count <> 1 OR
        distinct_skus <> 1 OR distinct_quantities <> 1 OR distinct_warehouses <> 2
    ) THEN
        RAISE EXCEPTION 'invalid TRANSFERENCIA movement';
    END IF;
END;
$$;

CREATE OR REPLACE FUNCTION validate_movement_consistency_trigger()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    target_movement_id bigint;
BEGIN
    IF TG_TABLE_NAME = 'movement_lines' THEN
        target_movement_id := COALESCE(NEW.movement_id, OLD.movement_id);
    ELSE
        target_movement_id := COALESCE(NEW.id, OLD.id);
    END IF;
    PERFORM validate_movement_consistency(target_movement_id);
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER movement_lines_consistency
AFTER INSERT OR UPDATE OR DELETE ON movement_lines
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION validate_movement_consistency_trigger();

CREATE CONSTRAINT TRIGGER movements_consistency
AFTER INSERT OR UPDATE ON movements
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION validate_movement_consistency_trigger();
