CREATE INDEX idx_movement_lines_sku_id ON movement_lines(sku_id);
CREATE INDEX idx_movement_lines_warehouse_id ON movement_lines(warehouse_id);
CREATE INDEX idx_asset_types_unit_code ON asset_types(unit_code);
CREATE INDEX idx_assets_asset_type_id ON assets(asset_type_id);
CREATE INDEX idx_assets_current_warehouse_id ON assets(current_warehouse_id);

