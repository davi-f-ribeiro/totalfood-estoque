UPDATE product_skus s
SET name = i.name || ' - ' || b.name || ' - ' ||
           trim(trailing '.' FROM trim(trailing '0' FROM s.content_quantity::text)) ||
           ' ' || i.unit_code
FROM inventory_items i, brands b
WHERE i.id=s.item_id AND b.id=s.brand_id AND s.brand_id<>0;

