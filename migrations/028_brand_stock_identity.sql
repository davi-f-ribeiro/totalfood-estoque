UPDATE stock_lots l
SET brand_id=s.brand_id
FROM movement_lines ml
JOIN product_skus s ON s.id=ml.sku_id
WHERE l.source_lot_id IS NULL
  AND l.source_movement_line_id=ml.id;

WITH RECURSIVE lineage AS (
    SELECT id,source_lot_id,brand_id
    FROM stock_lots
    WHERE source_lot_id IS NULL
  UNION ALL
    SELECT child.id,child.source_lot_id,parent.brand_id
    FROM stock_lots child
    JOIN lineage parent ON parent.id=child.source_lot_id
)
UPDATE stock_lots l
SET brand_id=x.brand_id
FROM lineage x
WHERE l.id=x.id
  AND l.brand_id IS NULL
  AND x.brand_id IS NOT NULL;

WITH one_brand AS (
    SELECT item_id,min(brand_id) AS brand_id
    FROM product_skus
    GROUP BY item_id
    HAVING count(DISTINCT brand_id)=1
)
UPDATE stock_lots l
SET brand_id=o.brand_id
FROM one_brand o
WHERE l.source_movement_line_id IS NULL
  AND l.item_id=o.item_id
  AND l.brand_id IS NULL;

CREATE INDEX idx_stock_lots_item_brand_warehouse_fefo
    ON stock_lots(item_id,brand_id,warehouse_id,expires_at,received_at,id);

WITH actual_brand AS (
    SELECT ml.movement_id,min(l.brand_id) AS brand_id
    FROM movement_lines ml
    JOIN movements m ON m.id=ml.movement_id AND m.movement_type='TRANSFERENCIA'
    JOIN stock_lot_allocations a ON a.movement_line_id=ml.id
    JOIN stock_lots l ON l.id=a.stock_lot_id
    WHERE ml.direction='OUT' AND l.brand_id IS NOT NULL
    GROUP BY ml.movement_id
    HAVING count(DISTINCT l.brand_id)=1
),
wrong AS (
    SELECT ab.movement_id,ab.brand_id,ml.item_id
    FROM actual_brand ab
    JOIN movement_lines ml ON ml.movement_id=ab.movement_id
    JOIN product_skus s ON s.id=ml.sku_id
    GROUP BY ab.movement_id,ab.brand_id,ml.item_id
    HAVING bool_or(s.brand_id<>ab.brand_id)
),
replacement AS (
    SELECT w.movement_id,
           (SELECT ps.id
              FROM product_skus ps
             WHERE ps.item_id=w.item_id AND ps.brand_id=w.brand_id
             ORDER BY ps.active DESC,ps.id
             LIMIT 1) AS sku_id
    FROM wrong w
)
UPDATE movement_lines ml
SET sku_id=r.sku_id
FROM replacement r
WHERE ml.movement_id=r.movement_id
  AND r.sku_id IS NOT NULL;

