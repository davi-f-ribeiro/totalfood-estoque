WITH raw_brand AS (
    SELECT id,
           CASE
             WHEN btrim(COALESCE(brand,'')) <> '' THEN btrim(brand)
             WHEN position(' - ' in COALESCE(name,'')) > 0
               THEN btrim(regexp_replace(name, '^.* - ', ''))
             ELSE btrim(COALESCE(name,''))
           END AS brand_name
    FROM product_skus
),
normalized AS (
    SELECT id,
           CASE WHEN upper(brand_name)='FIRMEZA' THEN 'Firmeza'
                ELSE brand_name END AS brand_name
    FROM raw_brand
    WHERE brand_name <> ''
)
INSERT INTO brands(name)
SELECT min(brand_name)
FROM normalized
GROUP BY lower(brand_name)
ON CONFLICT DO NOTHING;

