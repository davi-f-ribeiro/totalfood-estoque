-- Fase 3 da cadeia de suprimentos: expedição e comprovante.
-- Sai do estoque por movement_lines (SAÍDA); estas tabelas só dizem para quem, em qual
-- rota e com qual comprovante. Insumos e refeições prontas usam a mesma tabela de linhas.

ALTER TABLE vehicles
    ADD COLUMN ownership text NOT NULL DEFAULT 'propria'
        CHECK (ownership IN ('propria', 'alugada'));

CREATE TABLE delivery_orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id text NOT NULL UNIQUE CHECK (btrim(operation_id) <> ''),
    place_id bigint NOT NULL REFERENCES places(id),
    origin_warehouse_id bigint NOT NULL REFERENCES warehouses(id),
    day date NOT NULL,
    meal text CHECK (meal IN ('cafe', 'almoco', 'lanche', 'jantar')),
    due_at timestamptz NOT NULL,
    status text NOT NULL DEFAULT 'criado' CHECK (status IN
        ('criado', 'programado', 'despachado', 'em_rota', 'chegou', 'entregue', 'falhou', 'cancelado')),
    tracking_token text NOT NULL UNIQUE CHECK (length(tracking_token) >= 32),
    pod_required boolean NOT NULL DEFAULT true,
    notes text CHECK (notes IS NULL OR btrim(notes) <> ''),
    version bigint NOT NULL DEFAULT 1 CHECK (version > 0),
    created_by bigint REFERENCES users(id),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_delivery_orders_day ON delivery_orders (day, status);
CREATE INDEX idx_delivery_orders_place_id ON delivery_orders (place_id);

CREATE TABLE delivery_order_lines (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES delivery_orders(id) ON DELETE CASCADE,
    -- Refeição pronta: receita e porções. Insumo: item e quantidade. Nunca os dois.
    recipe_id bigint REFERENCES recipes(id),
    portions integer CHECK (portions > 0),
    item_id bigint REFERENCES inventory_items(id),
    quantity numeric(16,4) CHECK (quantity > 0),
    -- Ligação com a SAÍDA gravada no estoque: a rastreabilidade de lote passa por aqui.
    movement_line_id bigint UNIQUE REFERENCES movement_lines(id),
    CONSTRAINT delivery_line_kind CHECK (
        (recipe_id IS NOT NULL AND portions IS NOT NULL AND item_id IS NULL AND quantity IS NULL)
        OR
        (item_id IS NOT NULL AND quantity IS NOT NULL AND recipe_id IS NULL AND portions IS NULL)
    )
);

CREATE INDEX idx_delivery_order_lines_order_id ON delivery_order_lines (order_id);
CREATE INDEX idx_delivery_order_lines_item_id ON delivery_order_lines (item_id);

-- Histórico de status: só inserção. O status atual fica em delivery_orders.
CREATE TABLE delivery_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES delivery_orders(id),
    status text NOT NULL CHECK (status IN
        ('criado', 'programado', 'despachado', 'em_rota', 'chegou', 'entregue', 'falhou', 'cancelado')),
    operation_id text UNIQUE CHECK (operation_id IS NULL OR btrim(operation_id) <> ''),
    latitude numeric(9,6) CHECK (latitude BETWEEN -90 AND 90),
    longitude numeric(9,6) CHECK (longitude BETWEEN -180 AND 180),
    notes text CHECK (notes IS NULL OR btrim(notes) <> ''),
    user_id bigint REFERENCES users(id),
    occurred_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT delivery_events_coordinates_pair CHECK ((latitude IS NULL) = (longitude IS NULL))
);

CREATE INDEX idx_delivery_events_order_id ON delivery_events (order_id, occurred_at);

-- Comprovante: assinatura, foto ou código, guardado no próprio PostgreSQL (bytea).
CREATE TABLE delivery_proofs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES delivery_orders(id),
    event_id bigint NOT NULL UNIQUE REFERENCES delivery_events(id),
    kind text NOT NULL CHECK (kind IN ('assinatura', 'foto', 'codigo')),
    receiver_name text CHECK (receiver_name IS NULL OR btrim(receiver_name) <> ''),
    temperature_c numeric(5,2) CHECK (temperature_c BETWEEN -30 AND 100),
    content bytea CHECK (content IS NULL OR octet_length(content) <= 5242880),
    content_type text CHECK (content_type IS NULL OR content_type IN ('image/png', 'image/jpeg')),
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT delivery_proofs_content_pair CHECK ((content IS NULL) = (content_type IS NULL)),
    CONSTRAINT delivery_proofs_image_needs_content CHECK (kind = 'codigo' OR content IS NOT NULL)
);

CREATE INDEX idx_delivery_proofs_order_id ON delivery_proofs (order_id);

CREATE TABLE routes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    day date NOT NULL,
    vehicle_id bigint NOT NULL REFERENCES vehicles(id),
    driver_id bigint NOT NULL REFERENCES drivers(id),
    status text NOT NULL DEFAULT 'rascunho' CHECK (status IN
        ('rascunho', 'liberado', 'em_andamento', 'concluido', 'cancelado')),
    total_distance_m integer CHECK (total_distance_m >= 0),
    total_duration_s integer CHECK (total_duration_s >= 0),
    started_at timestamptz,
    completed_at timestamptz,
    version bigint NOT NULL DEFAULT 1 CHECK (version > 0),
    created_at timestamptz NOT NULL DEFAULT now()
);

-- Um veículo e um motorista não podem estar em duas rotas abertas no mesmo dia.
CREATE UNIQUE INDEX idx_routes_open_vehicle_day ON routes (vehicle_id, day)
    WHERE status IN ('rascunho', 'liberado', 'em_andamento');
CREATE UNIQUE INDEX idx_routes_open_driver_day ON routes (driver_id, day)
    WHERE status IN ('rascunho', 'liberado', 'em_andamento');

CREATE TABLE route_stops (
    route_id bigint NOT NULL REFERENCES routes(id) ON DELETE CASCADE,
    sequence integer NOT NULL CHECK (sequence > 0),
    order_id bigint NOT NULL UNIQUE REFERENCES delivery_orders(id),
    eta timestamptz,
    arrived_at timestamptz,
    distance_from_prev_m integer CHECK (distance_from_prev_m >= 0),
    duration_from_prev_s integer CHECK (duration_from_prev_s >= 0),
    PRIMARY KEY (route_id, sequence)
);

