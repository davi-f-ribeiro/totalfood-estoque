-- Requisições internas: pedido por item pai, reserva por SKU/depósito e
-- entrega física vinculada a uma saída real do WMS, com recebimento auditável.
CREATE TABLE material_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operation_id text NOT NULL UNIQUE CHECK(length(btrim(operation_id)) BETWEEN 1 AND 120),
  request_hash text NOT NULL,
  unit_name text NOT NULL CHECK(length(btrim(unit_name)) BETWEEN 1 AND 120),
  delivery_date date NOT NULL,
  production_date date NOT NULL,
  service text NOT NULL CHECK(service IN ('cafe','almoco','jantar')),
  notes text NOT NULL DEFAULT '' CHECK(length(notes) <= 1000),
  status text NOT NULL DEFAULT 'PENDENTE' CHECK(status IN
    ('PENDENTE','EM_SEPARACAO','ENTREGA_PARCIAL','ENTREGUE','RECEBIDA','CANCELADA')),
  created_by bigint NOT NULL REFERENCES users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE material_request_lines (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id bigint NOT NULL REFERENCES material_requests(id),
  item_id bigint NOT NULL REFERENCES inventory_items(id),
  quantity numeric(14,3) NOT NULL CHECK(quantity > 0),
  UNIQUE(request_id,item_id)
);

CREATE TABLE material_request_reservations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_line_id bigint NOT NULL REFERENCES material_request_lines(id),
  sku_id bigint NOT NULL REFERENCES product_skus(id),
  warehouse_id bigint NOT NULL REFERENCES warehouses(id),
  quantity numeric(14,3) NOT NULL CHECK(quantity > 0),
  remaining_quantity numeric(14,3) NOT NULL CHECK(remaining_quantity >= 0 AND remaining_quantity <= quantity),
  status text NOT NULL DEFAULT 'ATIVA' CHECK(status IN ('ATIVA','CONCLUIDA','LIBERADA')),
  operation_id text NOT NULL UNIQUE CHECK(length(btrim(operation_id)) BETWEEN 1 AND 120),
  request_hash text NOT NULL,
  created_by bigint NOT NULL REFERENCES users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  released_by bigint REFERENCES users(id),
  released_at timestamptz
);

CREATE INDEX idx_material_reservations_stock
 ON material_request_reservations(warehouse_id,sku_id)
 WHERE status='ATIVA';

CREATE TABLE material_request_deliveries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id bigint NOT NULL REFERENCES material_requests(id),
  reservation_id bigint NOT NULL REFERENCES material_request_reservations(id),
  quantity numeric(14,3) NOT NULL CHECK(quantity > 0),
  movement_id bigint NOT NULL UNIQUE REFERENCES movements(id),
  operation_id text NOT NULL UNIQUE CHECK(length(btrim(operation_id)) BETWEEN 1 AND 120),
  request_hash text NOT NULL,
  delivered_by bigint NOT NULL REFERENCES users(id),
  delivered_at timestamptz NOT NULL DEFAULT now(),
  received_by bigint REFERENCES users(id),
  received_at timestamptz
);

CREATE INDEX idx_material_deliveries_request ON material_request_deliveries(request_id);

CREATE TABLE material_request_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id bigint NOT NULL REFERENCES material_requests(id),
  actor_id bigint NOT NULL REFERENCES users(id),
  action text NOT NULL CHECK(action IN ('CRIADA','RESERVADA','LIBERADA','ENTREGUE','RECEBIDA','CANCELADA')),
  details text NOT NULL DEFAULT '',
  occurred_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_material_request_events ON material_request_events(request_id,id);

